"""The inventory port; routing and reply code do not know simulation details."""
from datetime import date
from typing import Protocol

from ..geo import Destination, Origin
from ..offer_models import Hotel, Leg, Transfer


class InventoryProvider(Protocol):
    def hotels_for(self, dest_id: str, count: int = 12) -> tuple[Hotel, ...]: ...
    def hotel_count(self) -> int: ...
    def hotel_price(self, hotel: Hotel, check_in: date, nights: int, adults: int, children: int) -> int: ...
    def transport_options(self, origin: Origin, dest: Destination, day: date, mode: str | None = None) -> list[Leg]: ...
    def transfer(self, hotel: Hotel, guests: int, train: bool = False, preferred: str | None = None) -> Transfer: ...
