def _operator() -> str:
    name = os.getenv("ODIN_OPERATOR_NAME", "").strip()
    address = os.getenv("ODIN_OPERATOR_ADDRESS", "").strip()
    email = os.getenv("ODIN_OPERATOR_EMAIL", "").strip()
    valid_email = bool(re.fullmatch(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}", email))
    contact = (f'<a href="mailto:{escape(email, quote=True)}">{escape(email)}</a>'
               if valid_email else "Контакт для обращений ещё не указан.")
    details = (f"<p><strong>Оператор:</strong> {escape(name)}</p>" if name else
               "<p>Оператор сервиса ещё не указан.</p>")
    details += f"<p><strong>Адрес:</strong> {escape(address)}</p>" if address else ""
    details += f"<p><strong>Обращения по персональным данным:</strong> {contact}</p>"
    if not (name and address and valid_email):
        details += ("<p>Это демонстрационная редакция. Перед доступом обычных пользователей необходимо "
                    "указать фактического оператора и контакты, проверить основания обработки, договоры "
                    "с поставщиками, размещение и сроки хранения. Сам по себе статус демо или запуск "
                    "на localhost не отменяет требования закона при обработке реальных данных.</p>")
    return details


